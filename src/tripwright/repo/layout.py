"""Repository format: where each canonical record lives and how it is written and read back without loss.

One repository per traveller, one folder per trip (`trips/<trip>/`), long-term content in `profile/` (CONTRACTS 4,
design 5.1). One record per file, written again only when its status changes; journals and the version ledger only
grow. `dump`/`load` are exact inverses for the index tables, so a database rebuilt from the files equals the one they
were written from. Paths that depend on a clock (raw message folders) are fixed when the file is first written and
found again by the record ID in the file name, so a later time-zone change never moves a file.
"""
from __future__ import annotations

import json
import re
from datetime import datetime, timezone
from zoneinfo import ZoneInfo

import yaml

FORMAT = 1
TRIPS = "trips"
PROFILE = "profile"
CANONICAL = ("events", "items", "facts", "decisions", "pending_checks", "undecided", "journal", "versions", "evidence",
             "profiles", "carry")
FOLDERS = {"items": "ledger/items", "facts": "ledger/facts", "decisions": "ledger/decisions",
           "pending_checks": "ledger/checks", "undecided": "ledger/questions", "carry": "ledger/carry"}
PLAN_FILES = ("places", "bookings")
TRIP_ID = re.compile(r"^[0-9A-Za-z][0-9A-Za-z._-]{0,79}$")
GITIGNORE = ".tripwright/\n*.sqlite3\n*.sqlite\n__pycache__/\n"
# Journals and version ledgers only grow, so a text merge of two sides is their union; generated files are taken from
# one side and regenerated by `tripwright sync`.
GITATTRIBUTES = ("trips/*/ledger/journal/*.jsonl merge=union\ntrips/*/plan/versions.jsonl merge=union\n"
                 "README.md merge=ours\ntrips/*/README.md merge=ours\ntrips/*/views/** merge=ours\n")


def trip_folder(trip_id: str) -> str:
    if not TRIP_ID.match(trip_id or ""):
        raise ValueError(f"Trip ID must be a folder name such as 2031-05-wien, got {trip_id!r}")
    return f"{TRIPS}/{trip_id}"


def dump(value) -> str:
    """YAML that loads back to exactly `value`; JSON (valid YAML) when PyYAML would change a scalar."""
    text = yaml.safe_dump(value, allow_unicode=True, sort_keys=False, width=120)
    if yaml.safe_load(text) != value:
        text = json.dumps(value, ensure_ascii=False, indent=2) + "\n"
    return text


def line(value) -> str:
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":")) + "\n"


def parse(path: str, text: str):
    try:
        return yaml.safe_load(text) if not path.endswith(".jsonl") else [json.loads(row) for row in text.splitlines() if row.strip()]
    except (yaml.YAMLError, json.JSONDecodeError) as error:
        raise ValueError(f"{path}: {error}") from None


def zoned(stamp: str, zone: str | None) -> datetime:
    moment = datetime.fromisoformat(stamp)
    return moment.astimezone(ZoneInfo(zone)) if zone else moment.astimezone(timezone.utc)


def suffix(record_id: str) -> str:
    return record_id.rsplit("-", 1)[-1]


# --- raw messages -------------------------------------------------------------

def raw_name(event: dict, zone: str | None) -> str:
    received = event["receipt"]["received_at"]
    utc = datetime.fromisoformat(received).astimezone(timezone.utc)
    speaker = re.sub(r"[^0-9A-Za-z_-]", "_", event["received"].get("speaker") or "unknown")
    return f"raw/{zoned(received, zone):%Y-%m-%d}/{utc:%Y%m%dT%H%M%SZ}-{speaker}-{suffix(event['id'])}.md"


def event_text(event: dict) -> str:
    received = event["received"]
    head = dict(id=event["id"], request_id=event["request_id"], received_at=event["receipt"]["received_at"],
                speaker=received.get("speaker"), nature=received["nature"], channel=received["channel"],
                native_ref=received.get("native_ref"), suspicious_words=received.get("suspicious_words") or [])
    return "---\n" + dump(head) + "---\n" + received["text"] + "\n"


def event_record(path: str, text: str) -> dict:
    if not text.startswith("---\n") or "\n---\n" not in text[4:]:
        raise ValueError(f"{path}: a message file starts with a front matter block")
    front, body = text[4:].split("\n---\n", 1)
    head = parse(path, front)
    if not body.endswith("\n"):
        raise ValueError(f"{path}: the message text must end with one newline")
    body = body[:-1]
    received = dict(text=body, nature=head["nature"], channel=head["channel"], native_ref=head.get("native_ref"),
                    speaker=head.get("speaker"), suspicious_words=head.get("suspicious_words") or [])
    receipt = dict(event_id=head["id"], received_text=body, nature=head["nature"], verbatim=head["nature"] == "user_verbatim",
                   received_at=head["received_at"], native_ref=head.get("native_ref"))
    return dict(id=head["id"], request_id=head["request_id"], received=received, receipt=receipt)


# --- records ------------------------------------------------------------------

def record_path(table: str, record: dict) -> str:
    extension = ".md" if table == "decisions" else ".yaml"
    return f"{FOLDERS[table]}/{record['id']}{extension}"


def decision_text(record: dict) -> str:
    """Decisions are Markdown for people; the front matter is the record, the body only repeats it for reading."""
    body = [f"# {record['question']}", "", f"选择：{record['choice']}（{record['decided_by']}）"]
    if record.get("reason"):
        body.append(f"理由：{record['reason']}")
    if record.get("revisit_when"):
        body.append(f"回头条件：{record['revisit_when'] if isinstance(record['revisit_when'], str) else json.dumps(record['revisit_when'], ensure_ascii=False)}")
    return "---\n" + dump(record) + "---\n" + "\n".join(body) + "\n"


def record_text(table: str, record: dict) -> str:
    return decision_text(record) if table == "decisions" else dump(record)


def record_from(table: str, path: str, text: str) -> dict:
    if table == "decisions":
        if not text.startswith("---\n") or "\n---\n" not in text[4:]:
            raise ValueError(f"{path}: a decision file starts with a front matter block")
        text = text[4:].split("\n---\n", 1)[0]
    record = parse(path, text)
    if not isinstance(record, dict) or "id" not in record:
        raise ValueError(f"{path}: not a record")
    return record


def journal_name(entry: dict) -> str:
    # UTC days: a later change of the trip's time zone must not move lines between append-only files.
    return f"ledger/journal/{zoned(entry['at'], None):%Y-%m-%d}.jsonl"


def evidence_path(record: dict) -> str:
    day = record.get("date") or zoned(record.get("fetched_at") or record.get("created_at"), None).strftime("%Y-%m-%d")
    return f"evidence/{day}/{record['id']}.yaml"


# --- plan -----------------------------------------------------------------------

def plan_files(plan: dict | None, trip_id: str) -> dict[str, str]:
    """`trip.yaml` and `plan/` for the committed plan. Without a plan yet, `trip.yaml` names the trip only."""
    if plan is None:
        return {"trip.yaml": dump(dict(id=trip_id))}
    metadata = {key: value for key, value in plan.items() if key not in ("days", "places", "bookings")}
    files = {"trip.yaml": dump(metadata)}
    for name in PLAN_FILES:
        files[f"plan/{name}.yaml"] = dump(plan.get(name, []))
    for day in plan.get("days", []):
        files[f"plan/days/{day['date']}.yaml"] = dump(day)
    return files


def plan_from(files: dict[str, str]) -> dict | None:
    """The plan in a trip folder's files, or None when the folder has no committed plan yet."""
    metadata = parse("trip.yaml", files["trip.yaml"]) if "trip.yaml" in files else None
    if not metadata or "plan/places.yaml" not in files:
        return None
    plan = dict(metadata)
    for name in PLAN_FILES:
        plan[name] = parse(f"plan/{name}.yaml", files.get(f"plan/{name}.yaml", "[]\n")) or []
    plan["days"] = [parse(path, text) for path, text in sorted(files.items())
                    if path.startswith("plan/days/") and path.endswith(".yaml")]
    return plan


def version_line(version: dict) -> dict:
    """The version ledger stores everything about a version except the plan, which is the `plan/` of its commit."""
    return {key: value for key, value in version.items() if key != "plan"} | {"plan_digest": plan_digest(version.get("plan"))}


def plan_digest(plan: dict | None) -> str | None:
    import hashlib

    if plan is None:
        return None
    return "sha256:" + hashlib.sha256(line(plan).encode()).hexdigest()[:16]


# --- whole trip -----------------------------------------------------------------

def trip_files(tables: dict[str, list[dict]], *, trip_id: str, zone: str | None, existing_raw: dict[str, str]) -> dict[str, str]:
    """Repository-relative path → text for one trip's canonical files (views are block B's).

    `existing_raw` maps message IDs to the path their file already has, so it is never moved."""
    base = trip_folder(trip_id)
    files: dict[str, str] = {}
    for event in tables["events"]:
        if "received" in event:
            path = existing_raw.get(event["id"]) or f"{base}/{raw_name(event, zone)}"
            files[path] = event_text(event)
    changes = {event["id"]: event for event in tables["events"] if "received" not in event}
    journals: dict[str, list[str]] = {}
    for entry in tables["journal"]:
        journals.setdefault(f"{base}/{journal_name(entry)}", []).append(line(dict(entry=entry, change=changes.get(entry["event"]))))
    files.update({path: "".join(rows) for path, rows in journals.items()})
    for table in FOLDERS:
        for record in tables[table]:
            files[f"{base}/{record_path(table, record)}"] = record_text(table, record)
    for record in tables["evidence"]:
        files[f"{base}/{evidence_path(record)}"] = dump(record)
    versions = sorted(tables["versions"], key=lambda version: version["number"])
    files[f"{base}/plan/versions.jsonl"] = "".join(line(version_line(version)) for version in versions)
    current = versions[-1]["plan"] if versions else None
    files.update({f"{base}/{path}": text for path, text in plan_files(current, trip_id).items()})
    return files


def raw_paths(paths) -> dict[str, str]:
    """Message ID suffix → path, for every raw message file among `paths`."""
    found = {}
    for path in paths:
        match = re.search(r"/raw/[^/]+/[^/]+-([0-9a-z]+)\.md$", path)
        if match:
            found[match.group(1)] = path
    return found


def trip_tables(files: dict[str, str], *, plans: dict[str, dict] | None = None) -> dict:
    """Index tables from one trip folder's files (paths relative to the folder).

    Returns `{tables, problems, manual_plan}`. A file that does not parse is listed in `problems` and skipped, so the
    caller can keep its previous valid content. `plans` maps version IDs to their plans from history; a version whose
    plan is neither there nor equal to the folder's `plan/` keeps `plan: None` and is reported. When the folder's
    `plan/` differs from the last version's plan, someone edited it without the tool: it is returned as `manual_plan`."""
    problems: list[str] = []
    tables: dict[str, list[dict]] = {name: [] for name in CANONICAL if name != "profiles"}
    received = []
    for path, text in sorted(files.items()):
        try:
            if path.startswith("raw/") and path.endswith(".md"):
                received.append(event_record(path, text))
            elif path.startswith("evidence/") and path.endswith(".yaml"):
                tables["evidence"].append(record_from("evidence", path, text))
            else:
                table = next((name for name, folder in FOLDERS.items() if path.startswith(folder + "/")), None)
                if table:
                    tables[table].append(record_from(table, path, text))
        except (ValueError, KeyError, TypeError) as error:
            problems.append(str(error) if str(error).startswith(path) else f"{path}: {error}")
    changes = []
    for path, text in sorted((path, text) for path, text in files.items() if path.startswith("ledger/journal/")):
        try:
            for row in parse(path, text):
                tables["journal"].append(row["entry"])
                if row.get("change"):
                    changes.append(row["change"])
        except (ValueError, KeyError, TypeError) as error:
            problems.append(f"{path}: {error}")
    tables["journal"].sort(key=lambda entry: entry["at"])
    received.sort(key=lambda event: (event["receipt"]["received_at"], event["id"]))
    # One events table holds messages and change records in the order they happened.
    tables["events"] = sorted(received + changes, key=lambda event: event.get("receipt", {}).get("received_at") or event["created_at"])
    order = {entry["record_id"]: index for index, entry in reversed(list(enumerate(tables["journal"])))}
    for table in ("items", "facts", "decisions", "pending_checks", "carry"):
        tables[table].sort(key=lambda record: (order.get(record["id"], len(order)), record["id"]))
    tables["undecided"].sort(key=lambda record: (record.get("since") or "", record["id"]))
    tables["evidence"].sort(key=lambda record: (record.get("fetched_at") or record.get("created_at") or "", record["id"]))
    current_plan = None
    try:
        current_plan = plan_from(files)
    except ValueError as error:
        problems.append(str(error))
    lines = []
    if "plan/versions.jsonl" in files:
        try:
            lines = sorted(parse("plan/versions.jsonl", files["plan/versions.jsonl"]), key=lambda version: version["number"])
        except ValueError as error:
            problems.append(str(error))
    for row in lines:
        version = {key: value for key, value in row.items() if key != "plan_digest"}
        plan = (plans or {}).get(version["id"])
        if plan is None and current_plan is not None and plan_digest(current_plan) == row.get("plan_digest"):
            plan = current_plan
        if plan is not None and plan_digest(plan) != row.get("plan_digest"):
            plan = None
        if plan is None:
            problems.append(f"plan/versions.jsonl: the plan of {version['id']} is not in this history")
        version["plan"] = plan
        tables["versions"].append(version)
    latest = lines[-1]["plan_digest"] if lines else None
    manual = current_plan if current_plan is not None and plan_digest(current_plan) != latest else None
    return dict(tables=tables, problems=problems, manual_plan=manual)
